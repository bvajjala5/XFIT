// Copies the project's `.env` + service account into the folder the packaged
// macOS/Windows/Linux app reads at runtime, so the built app can find them no
// matter where it lives. Run with: npm run setup:app
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import dotenv from 'dotenv'
import { userDataDir } from '../electron/firebase.js'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcEnv = path.join(root, '.env')

if (!fs.existsSync(srcEnv)) {
  console.error(`No .env found at ${srcEnv}. Copy .env.example to .env and fill it in first.`)
  process.exit(1)
}

const parsed = dotenv.parse(fs.readFileSync(srcEnv))
const rawServiceAccount = parsed.FIREBASE_SERVICE_ACCOUNT
if (!rawServiceAccount) {
  console.error('FIREBASE_SERVICE_ACCOUNT is not set in .env — nothing to install.')
  process.exit(1)
}

const serviceAccountPath = path.isAbsolute(rawServiceAccount)
  ? rawServiceAccount
  : path.resolve(root, rawServiceAccount)

if (!fs.existsSync(serviceAccountPath)) {
  console.error(`Service account file not found at ${serviceAccountPath}`)
  process.exit(1)
}

const destination = userDataDir()
fs.mkdirSync(destination, { recursive: true })
fs.copyFileSync(serviceAccountPath, path.join(destination, 'service-account.json'))
fs.writeFileSync(
  path.join(destination, '.env'),
  [
    '# Uttar Fitness Admin Control Hub — per-user credentials (used by the packaged app).',
    '# Generated by `npm run setup:app`. Never commit or share this file.',
    '',
    `FIREBASE_PROJECT_ID=${parsed.FIREBASE_PROJECT_ID || ''}`,
    'FIREBASE_SERVICE_ACCOUNT=./service-account.json',
    '',
  ].join('\n'),
)

console.log(`Installed credentials into:\n  ${destination}`)
